#!/usr/bin/env node
/**
 * Snapshot Renovate's deprecated-key rename map into
 * src/data/migrations.generated.ts.
 *
 * The resulting file is committed to git. Runtime code in src/ never imports
 * the renovate package; this script is the one exception (it's a build-time
 * step). Regenerate after bumping the `renovate` devDependency.
 *
 * Source of truth: `MigrationsService.renamedProperties` — a static
 * `Map<oldKey, newKey>` populated at class-load time. This is the
 * "RenamePropertyMigration" subset of Renovate's migration registry; value
 * coercions and structural transformations are NOT included on purpose
 * (lint_config flags only simple renames; users with value/structural
 * deprecations get pointed at migrate_config).
 */
import { writeFile, lstat } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { createRequire } from "node:module";

async function refuseIfSymlink(target) {
  try {
    const stat = await lstat(target);
    if (stat.isSymbolicLink()) {
      console.error(
        `refusing to write to ${path.relative(process.cwd(), target)}: destination is a symlink`,
      );
      process.exit(1);
    }
  } catch (err) {
    if (err && err.code !== "ENOENT") throw err;
  }
}

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT_PATH = path.resolve(__dirname, "../src/data/migrations.generated.ts");

await refuseIfSymlink(OUT_PATH);

const require = createRequire(import.meta.url);
const renovatePkg = require("renovate/package.json");

const { MigrationsService } = await import(
  "renovate/dist/config/migrations/migrations-service.js"
);

const entries = [...MigrationsService.renamedProperties.entries()]
  .map(([oldKey, newKey]) => ({ oldKey, newKey }))
  .sort((a, b) => a.oldKey.localeCompare(b.oldKey));

const header = `// AUTO-GENERATED by scripts/generate-migrations.mjs from renovate@${renovatePkg.version}.
// Do not edit by hand. Run \`npm run generate:migrations\` to refresh.
`;

const body = `
export const RENOVATE_VERSION = ${JSON.stringify(renovatePkg.version)};

export interface DeprecatedKeyEntry {
  /** Key as it appeared in old configs. */
  readonly oldKey: string;
  /** Current key that replaces it. */
  readonly newKey: string;
}

/**
 * Deprecated config keys with their current replacement. Sourced from
 * Renovate's \`MigrationsService.renamedProperties\` — the "RenamePropertyMigration"
 * subset only. Value coercions (e.g. \`stabilityDays\` → \`minimumReleaseAge\`)
 * and structural transformations are deliberately excluded; \`migrate_config\`
 * is the right tool for those.
 */
export const DEPRECATED_KEYS: readonly DeprecatedKeyEntry[] = Object.freeze(${JSON.stringify(entries, null, 2)});
`;

await writeFile(OUT_PATH, header + body);
console.log(
  `Wrote ${entries.length} renamed properties from renovate@${renovatePkg.version} to ${path.relative(process.cwd(), OUT_PATH)}`,
);
